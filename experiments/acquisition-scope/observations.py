"""Actual observation reads with literal native/receipt/input expectations.

The existing binding launcher owns cloned databases, containers and cleanup.
No expected result is generated by production Rust or from observed native bytes.
"""
import hashlib
import json


def expected(dataset, witness, private, cbor):
    be = lambda n, width=8: n.to_bytes(width, 'big')
    sha = lambda value: hashlib.sha256(value).digest()
    domains = {2: bytes([65])*16, 4: bytes([64])*16, 8: bytes([68])*16}
    if witness: domains.update({1: bytes([70])*16, 3: bytes([71])*16, 5: bytes([72])*16})
    ref = lambda kind, n=1: [dataset, kind, domains[kind], n]
    ref_key = lambda kind, n=1: dataset + be(kind, 2) + domains[kind] + be(n)
    src = lambda n: [dataset, 0, 1, n]
    src_key = lambda n: dataset + be(0, 4) + be(1) + be(n)
    scope, slot = ref(4), bytes([66])*16
    manifest = (bytes.fromhex('01010001000100010001') + dataset + be(0)
        + bytes([61])*16 + be(0, 4) + be(1) + bytes([63])*16 + bytes([67])*16
        + be(1) + bytes([1, len(domains)])
        + b''.join(be(k, 2) + v for k,v in sorted(domains.items())))
    rows = {('default', b'\x01\x01'): manifest}
    definitions = [(4, 1, 'visibility', {'class': 'private' if private else 'public'}),
        (4, 2, 'visibility', {'class': 'public' if private else 'private'}),
        (2, 1, 'observer', {'clock':'system-utc', 'vantage':'source-fixture', 'software':None,
            'method_id':None, 'public_key':None, 'route_class':None, 'software_version':None})]
    if witness:
        definitions += [(1, 1, 'endpoint', {'url':'wss://source.example/events'}),
            (3, 1, 'access-scope', {'class':'public', 'label':None, 'visibility_scope_id':scope}),
            (5, 1, 'event-verification', {
                'input':'nip01-event/1', 'algorithm':'sha256-bip340',
                'capability':'event-id-and-signature', 'output_unit':'verification-result',
                'failure_taxonomy':'bigbrotr-nip01-verifier/1', 'algorithm_version':1,
                'protocol_revision':'a2494f4f81d46684e5814a9bf35e2b1df978f955'})]
    refs, entries = [], []
    for sequence, (kind, ordinal, schema, value) in enumerate(definitions, 1):
        descriptor = [1, schema, 1, value]
        mapping = [ref(kind, ordinal), *descriptor]
        fact = b'bigbrotr/fact/1\0' + cbor([src(sequence), 'dictionary', 1, scope, 123, mapping])
        digest, canonical = sha(fact), cbor(descriptor)
        refs.append([src(sequence), digest])
        entries.append(['dictionary', 1, mapping])
        rows['facts', b'\x01\x20' + src_key(sequence)] = b'\x01\x20' + digest + fact
        rows['default', b'\x01\x04' + ref_key(kind, ordinal)] = b'\x01\x04' + src_key(sequence) + digest
        rows['default', b'\x01\x05' + dataset + be(kind, 2) + sha(canonical) + ref_key(kind, ordinal)] = b'\x01\x05' + canonical
        rows['default', b'\x01\x03' + dataset + be(kind, 2) + domains[kind]] = b'\x01\x03' + be(ordinal)
    n = len(refs)
    request = b'bigbrotr/producer-request/1\0' + cbor([[slot,1,1], 'admit-evidence', 1, [1,scope,entries]])
    receipt = b'bigbrotr/receipt/1\0' + cbor([1,[slot,1,1],sha(request),[dataset,0,1,bytes([67])*16,1],refs,refs])
    rows['default', b'\x01\x02' + dataset + be(0,4) + be(1)] = b'\x01\x02' + be(n)
    rows['facts', b'\x01\x21' + src_key(1)] = b'\x01\x21' + be(n) + sha(b'bigbrotr/admission-batch/1\0' + cbor([dataset,0,1,1,n,refs]))
    rows['receipts', b'\x01\x30' + slot + be(1) + be(1)] = receipt
    rows['receipts', b'\x01\x31' + slot + be(1)] = b'\x01\x31' + be(1) + be(0) + be(0)
    return sorted((cf,k,v) for (cf,k),v in rows.items()), request, receipt


def run(context):
    lab, pg, client, output, source, rows, clone, report, save, require, cbor = (
        context[k] for k in ('lab','pg','client','output','SOURCE','rows','clone','report','save','require','oracle'))
    cbor = cbor.cbor
    report['not_run'] = ['late/lost/cancelled ROLLBACK delivery', 'socket-to-admission/M1',
        'general dictionary allocation or cross-scope grants', 'load/aged state, capacity, arm64, release']
    for name in ['off','on','private-on','expired','cancelled','policy']:
        database = clone('observation-' + name, 'bb_source_template')
        config = lab.config(output, dict(pg, client=client), database,
                            endpoint='127.0.0.1:5432', boundary='loopback')
        upgraded = lab.cli(dict(pg, client=client), 'migrate', 'apply', '--file', config,
            '--user', 'bigbrotr_migrator', '--password-ref', 'file:/run/secrets/migrator', '--target', '24')
        (output / f'{name}-migrate.stdout').write_text(upgraded.stdout)
        (output / f'{name}-migrate.stderr').write_text(upgraded.stderr)
        require(upgraded.returncode == 0, 'fixture-current-schema')
        before = rows(database)
        require(len(before) == 67 and not before['owner_epochs'] and not before['producer_requests'], 'fresh-current-clone')
        lab.write_json(output / f'{name}-before.json', before)
        result = lab.docker('exec', client, '/build/ingest_bootstrap_probe', 'source-observation-' + name,
            database, '/run/secrets/application', '/lab/' + name, check=False, timeout=60)
        (output / f'{name}.stdout').write_text(result.stdout)
        (output / f'{name}.stderr').write_text(result.stderr)
        require(result.returncode == 0 and not result.stderr, 'actual-observation-' + name)
        messages = [json.loads(line) for line in result.stdout.splitlines()]
        first, last = messages[1], messages[-1]
        require(first['event'] == 'observation-before' and last['event'] == 'observation-finished'
            and last['status'] == 'PASS' and first['state'] == last['state'], 'all-operation-state-unchanged')
        require(len(first['state']['control_tables']) == 67, 'complete-operation-census')
        after = rows(database)
        lab.write_json(output / f'{name}-after.json', after)
        dataset = bytes.fromhex(after['datasets'][0]['dataset_id'][2:])
        wanted, original, receipt = expected(dataset, name.endswith('on'), name == 'private-on', cbor)
        dumped = lab.docker('exec', client, '/build/ingest_bootstrap_probe', 'dump', '/lab/' + name)
        (output / f'{name}-native.json').write_text(dumped.stdout)
        actual = [(r['cf'],bytes.fromhex(r['key']),bytes.fromhex(r['value'])) for r in json.loads(dumped.stdout)['rows']]
        require(actual == wanted, 'literal-full-native-bytes')
        inputs = list((output / name / 'producer-inputs-v1').glob('*.cbor'))
        require(len(inputs) == 1 and inputs[0].read_bytes() == original, 'literal-original-input')
        require(len(after['producer_requests']) == len(after['producer_outcomes']) == 1, 'no-read-mutation')
        require(after['producer_outcomes'][0]['outcome_bytes'] == '\\x' + receipt.hex(), 'literal-PG-receipt')
        reads = [m for m in messages if m['event'] == 'observation-read']
        require(len(reads) == (2 if name in ('off','on','private-on') else 0), 'actual-read-count')
        for read in reads:
            require(read['witness'] == name.endswith('on') and read['clock']['uncertainty_us'] is None
                and read['clock']['clock_id'] == read['observer'] and int(read['clock']['resolution_us']) > 0,
                'actual-clock-attribution')
        require(lab.sql(pg,database,"SELECT count(*) FROM pg_stat_activity WHERE datname=current_database() AND usename='bigbrotr_control'") == '0', 'unjoined-driver')
        report['cases'].append(dict(name=name, status='PASS', native_rows=len(actual),
            dictionaries=6 if name.endswith('on') else 3, zero_operation_writes=True))
        save()
