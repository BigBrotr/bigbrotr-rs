pub fn command() -> clap::Command {
    clap::Command::new("BigBrotr")
        .bin_name("bigbrotr")
        .version(concat!(env!("CARGO_PKG_VERSION"), " (", env!("BIGBROTR_BUILD_TARGET"), ")"))
        .about("BigBrotr: verifiable Nostr archive and observatory")
        .after_help("Implementation in progress. Use build-info to inspect this artifact's available capabilities.")
        .arg_required_else_help(true)
        .subcommand_required(true)
        .disable_help_subcommand(true)
        .subcommand(clap::Command::new("build-info").about("Print embedded build identity as JSON"))
        .subcommand(crate::config::command())
        .subcommand(crate::config::doctor_command())
        .subcommand(crate::interfaces::migrations::command())
        .subcommand(crate::interfaces::access::command())
        .subcommand(crate::interfaces::jobs::command())
        .subcommand(crate::interfaces::archive::command())
        .subcommand(crate::interfaces::export::command())
        .subcommand(crate::interfaces::serve::command())
        .subcommand(crate::interfaces::serve::ingest_command())
        .subcommand(crate::interfaces::serve::index_command())
        .subcommand(clap::Command::new("event")
            .about("Inspect a signed event without admitting it to storage")
            .subcommand_required(true)
            .disable_help_subcommand(true)
            .subcommand(clap::Command::new("verify")
                .about("Verify one bounded Nostr JSON event from stdin; output its complete normalized JSON")
                .after_help("Exit codes: 0 verified, 1 I/O failure, 2 usage, 3 invalid event, 4 excluded by input limits. No durable admission or source policy is implied.")))
}
